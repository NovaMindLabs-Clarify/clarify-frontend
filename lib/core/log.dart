import 'package:flutter/foundation.dart';

/// Диагностический вывод приложения.
///
/// Заменяет россыпь `print(...)` по коду (B9 в docs/AUDIT_2026-09-04.md).
/// Дело не только в замечании анализатора: `print` работает и в собранном
/// релизе, то есть в системный вывод пользователя утекали и тексты ошибок, и
/// куски его данных («Ошибка обновления статуса: …»). Плюс это лишняя работа
/// на каждом кадре там, где логи никто не читает.
///
/// В отладке всё видно как раньше, в релизной сборке — тишина. Отдельного
/// пакета-логгера сознательно не заводим: уровней нужно ровно два, а лишняя
/// зависимость в приложении, которое собирается под Windows, веб и мобильные,
/// стоит дороже, чем эти десять строк.
void logDebug(String message) {
  if (kReleaseMode) return;
  debugPrint(message);
}

/// То же, но для ошибок — отдельным вызовом, чтобы их было видно в потоке
/// обычных сообщений и чтобы позже можно было добавить отправку в трекер, не
/// переписывая места вызова.
void logError(String message, [Object? error]) {
  if (kReleaseMode) return;
  debugPrint(error == null ? '[ошибка] $message' : '[ошибка] $message: $error');
}

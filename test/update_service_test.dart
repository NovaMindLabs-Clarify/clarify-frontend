import 'package:flutter_test/flutter_test.dart';
import 'package:frontend/services/update_service.dart';

/// Сравнение версий (проверка обновлений).
///
/// Тест не про арифметику, а про одну конкретную ловушку: сравнение версий
/// строками даёт '1.10.0' < '1.9.0', потому что '1' < '9'. Сломалось бы это
/// ровно на десятом релизе и выглядело бы как «обновления перестали
/// приходить» — то есть в момент, когда чинить уже поздно, потому что
/// проверка живёт внутри уже розданных сборок.
///
/// В этом проекте на такой же ловушке уже обожглись с датами: строка
/// '31.08.2026' лексикографически больше '05.09.2026'.
void main() {
  int cmp(String a, String b) => UpdateService.compareVersions(a, b);

  group('сравнение версий', () {
    test('равные версии', () {
      expect(cmp('1.0.0', '1.0.0'), 0);
    });

    test('старшая мажорная больше', () {
      expect(cmp('2.0.0', '1.9.9'), 1);
      expect(cmp('1.9.9', '2.0.0'), -1);
    });

    test('двузначная минорная больше однозначной', () {
      // Та самая ловушка: строками было бы наоборот.
      expect(cmp('1.10.0', '1.9.0'), 1);
      expect(cmp('1.9.0', '1.10.0'), -1);
    });

    test('двузначный патч больше однозначного', () {
      expect(cmp('1.0.10', '1.0.9'), 1);
    });

    test('номер сборки после плюса не участвует', () {
      // pubspec хранит версию как 1.0.0+1, сервер отдаёт 1.0.0 — они должны
      // считаться одинаковыми, иначе приложение вечно предлагает обновиться
      // на само себя.
      expect(cmp('1.0.0+1', '1.0.0'), 0);
      expect(cmp('1.0.0', '1.0.0+17'), 0);
    });

    test('разная длина номера', () {
      expect(cmp('1.2', '1.2.0'), 0);
      expect(cmp('1.2.1', '1.2'), 1);
    });

    test('мусор не роняет сравнение', () {
      expect(cmp('', '1.0.0'), -1);
      expect(cmp('не версия', '1.0.0'), -1);
    });
  });
}
